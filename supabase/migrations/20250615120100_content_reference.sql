-- Phase 1: Accounts + Cloud Sync + Leaderboards — content reference
--
-- A deliberately small mirror of the facts leaderboard validation needs
-- from the app's static content (content/workouts/workout.json,
-- content/monsters/*.json) — NOT the Kettleborn content JSON itself.
-- The app's content files remain the single source of truth for
-- everything gameplay-related (exercises, damage, structure); this is
-- read-only reference data so the backend can answer two questions
-- without trusting the client:
--   1. does this workout_id/hunt_id combination actually exist?
--   2. is a submitted elapsed_seconds/weight_kg even plausible for it?
--
-- Regenerating this table: the INSERT statements below were generated by
-- reading content/workouts/workout.json and content/monsters/*.json
-- directly (every workout_id, hunt_id, monster_id, target_time_seconds,
-- gearWeightKg, gearCount and rounds value here is real game data, not
-- placeholder content). If workout content changes in a future app
-- release, re-run the same extraction and ship a new migration that
-- upserts the changed rows — the ON CONFLICT clauses make re-running
-- this exact file safe, but a genuine content change should still be its
-- own dated migration, not an edit to this one (see content_version
-- notes in supabase/README.md).

create table public.content_workouts (
  workout_id text primary key,
  target_time_seconds integer not null,
  -- Plausibility floor for leaderboard eligibility (not a hard gate on
  -- history — see content_hunts/workout_results below). 30% of target
  -- time, minimum 10s. A crude heuristic, not anti-cheat.
  min_elapsed_seconds integer not null,
  gear_weight_kg numeric not null,
  -- Reuses the exact [0.5, 1.5] ratio engines/progress/progressionEngine.ts
  -- already clamps XP's weightBonus to, against the same gearWeightKg
  -- baseline — not a new, separately-invented tolerance band.
  min_weight_kg numeric not null,
  max_weight_kg numeric not null,
  gear_count smallint not null,
  rounds integer not null
);

comment on table public.content_workouts is
  'Read-only mirror of enough of content/workouts/workout.json to validate leaderboard submissions. The app content JSON remains authoritative for gameplay.';

create table public.content_hunts (
  hunt_id text primary key,
  monster_id text not null,
  workout_id text not null references public.content_workouts (workout_id),
  encounter_order smallint not null
);

comment on table public.content_hunts is
  'Read-only mirror of each monster''s hunts[] (content/monsters/*.json) — monster_id/workout_id/order only.';

alter table public.content_workouts enable row level security;
alter table public.content_hunts enable row level security;

-- Read-only reference data: every authenticated client can read it (the
-- insert trigger in the next migration needs to look workouts up), but
-- NO policy grants insert/update/delete to `authenticated` — this table
-- is written only by migrations (as the `postgres`/migration role, which
-- bypasses RLS entirely), never by the app.
create policy "content_workouts_select_all"
  on public.content_workouts
  for select
  to authenticated
  using (true);

create policy "content_hunts_select_all"
  on public.content_hunts
  for select
  to authenticated
  using (true);

grant select on public.content_workouts to authenticated;
grant select on public.content_hunts to authenticated;

